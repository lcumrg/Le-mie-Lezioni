import { useNavigate } from 'react-router-dom'
import { useApp } from '../contexts/AppContext'
import { useToast } from '../contexts/ToastContext'
import {
  onLezioniSettimana,
  onAssegnazioni,
  onOrari,
  onPercorsi,
  onUnita,
  onVacanze,
  onRicorrenze,
  onDistribuzioni,
  addLezione,
  updateLezione,
  deleteLezione,
  setDistribuzioniClasse,
} from '../lib/firestore'
import { getWeekRange } from '../lib/settimane'
import {
  STATO_LEZIONE,
  GIORNI_LABEL,
  GIORNI_SHORT,
} from '../lib/costanti'
